#!/usr/bin/env python3
"""E002-446: fixed-geometry human-frame edge-span triage; NEVER anatomical certification.

A false eyelid-like candidate can be generated by a non-eyelid dark stripe. The
instrument measures candidate edge spans and reports nuisance failures, not
blink, aperture, velocity, or physical time. No images or per-frame series leave
its execution environment.
"""
import argparse
import json
import tempfile
from pathlib import Path

import numpy as np

from e002_441_human_acquisition import download
from e002_444_human_optical_motion import WIDTH, HEIGHT, grayscale_frames, verify_and_extract

LIMIT = 3000
X0, X1 = 80, 240
STRIP = 10
UPPER = (55, 145)
LOWER = (146, 235)
MIN_CONTRAST = 12.0
MIN_STRIPS = 12
MAX_IQR = 12.0


def _percentile(values, p):
    return float(np.percentile(np.asarray(values, dtype=float), p)) if values else None


def edge_span(frame):
    """Candidate row-edge separation in PIXELS; cannot identify anatomy."""
    arr = np.asarray(frame)
    if arr.shape != (HEIGHT, WIDTH) or arr.dtype != np.uint8:
        raise ValueError("invalid frame shape or dtype")
    profile = np.median(arr[:, X0:X1].reshape(HEIGHT, (X1-X0)//STRIP, STRIP), axis=2)
    smoothed = np.stack([np.convolve(profile[:, k], np.ones(5)/5, mode="same")
                         for k in range(profile.shape[1])], axis=1)
    gradient = smoothed[1:] - smoothed[:-1]
    us, ls = [], []
    for k in range(profile.shape[1]):
        ug = gradient[UPPER[0]:UPPER[1], k]
        lg = gradient[LOWER[0]:LOWER[1], k]
        ui, li = int(np.argmin(ug)) + UPPER[0], int(np.argmax(lg)) + LOWER[0]
        if -gradient[ui, k] >= MIN_CONTRAST and gradient[li, k] >= MIN_CONTRAST:
            us.append(ui)
            ls.append(li)
    if len(us) < MIN_STRIPS:
        return None
    u, l = float(np.median(us)), float(np.median(ls))
    if not (12 <= l-u <= 150):
        return None
    if np.percentile(us, 75)-np.percentile(us, 25) > MAX_IQR:
        return None
    if np.percentile(ls, 75)-np.percentile(ls, 25) > MAX_IQR:
        return None
    interior = np.median(profile[int(u)+5:int(l)-5])
    outside = np.median(np.vstack((profile[int(u)-15:int(u)-5], profile[int(l)+5:int(l)+15])))
    if not (np.isfinite(interior) and np.isfinite(outside) and outside-interior >= 15):
        return None
    return (u, l)


def summarize(frames, limit=LIMIT):
    if limit < 3:
        raise ValueError("insufficient frame count")
    spans, jumps, valid = [], [], 0
    prev = None
    count = 0
    for frame in frames:
        if count >= limit:
            break
        candidate = edge_span(frame)
        if candidate is not None:
            valid += 1
            spans.append(candidate[1]-candidate[0])
        if candidate is not None and prev is not None:
            jumps.append(max(abs(candidate[0]-prev[0]), abs(candidate[1]-prev[1])))
        prev = candidate
        count += 1
    if count != limit:
        raise ValueError("fewer decoded frames than frozen window")
    fraction = valid/limit
    jump_fraction = sum(v >= 20 for v in jumps)/len(jumps) if jumps else None
    triage = ("ANNOTATION_TRIAGE_ONLY_NOT_ANATOMY"
              if fraction >= .5 and jump_fraction is not None and jump_fraction <= .1
              else "REJECT_UNSTABLE_OR_INSUFFICIENT_EDGE_PROXY")
    return {
        "frames": limit,
        "edge_span_candidate_frames": valid,
        "edge_span_candidate_fraction": fraction,
        "candidate_span_px_p05": _percentile(spans, 5),
        "candidate_span_px_median": _percentile(spans, 50),
        "candidate_span_px_p95": _percentile(spans, 95),
        "consecutive_candidate_pairs": len(jumps),
        "candidate_edge_jump_px_p95": _percentile(jumps, 95),
        "candidate_edge_jump_ge_20_fraction": jump_fraction,
        "triage_screen": triage,
        "non_anatomical_stripe_counterexample": "CAN_PASS_SAME_GEOMETRIC_SCREEN",
        "anatomical_aperture_measured": False,
        "event_frame_alignment_authenticated": False,
        "physical_shutter_timing_authenticated": False,
        "physiological_velocity_bound_established": False,
        "e002_371_physical_validation": "NOT_ESTABLISHED",
        "product_claim": "ABSTAIN_UNCALIBRATED",
        "physical_release_authorized": False,
    }


def run(archive):
    with tempfile.TemporaryDirectory() as td:
        video = Path(td) / "S19.avi"
        times = verify_and_extract(archive, video)
        if len(times) != 56911:
            raise ValueError("unexpected event count")
        result = summarize(grayscale_frames(video, count=LIMIT))
    return {"experiment": "E002-446", "source": "MD5-verified S19 human video",
            "pilot_only": True, "S21_S22_holdouts_inspected": False,
            "measurement": "fixed image-edge span in pixels; NOT anatomical aperture",
            "summary": result}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--zip", type=Path)
    p.add_argument("--output", type=Path, required=True)
    a = p.parse_args()
    with tempfile.TemporaryDirectory() as td:
        z = a.zip or Path(td) / "S19.zip"
        if a.zip is None:
            download("S19", z)
        result = run(z)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(json.dumps(result, sort_keys=True, indent=2)+"\n")
    print(json.dumps({"experiment": "E002-446", "triage_screen": result["summary"]["triage_screen"],
                      "physical_release_authorized": False}))


if __name__ == "__main__":
    main()
